"""Export a readable review packet for the batch curation queue.

The packet is the working document for manual review: it lists every automatic
candidate with its full abstract and the sentence that triggered the match, plus
a summary of the rows still waiting for review.

Usage:
    .venv/Scripts/python.exe scripts/curation/02_export_review_packet.py
"""
from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from graphambicardio.curation import batch_review  # noqa: E402
from graphambicardio.io_utils import read_csv, today  # noqa: E402
from graphambicardio.literature.pubmed import efetch  # noqa: E402

QUEUE = ROOT / "literature" / "curated" / "batch_chd_queue.csv"
REVIEW = ROOT / "literature" / "curated" / "batch_chd_review.csv"
OUT = ROOT / "reports" / "batch_chd_review_packet.md"


def main() -> None:
    queue = read_csv(QUEUE)
    approved = [r for r in queue if r.get("status") == "approved"]
    waiting = [r for r in queue if r.get("status") != "approved"]
    pmids = sorted({r["pmid"] for r in approved if r.get("pmid")})
    studies = {s.pmid: s for s in efetch(pmids)}
    reviews = batch_review.load_reviews(REVIEW)
    verified = sum(1 for r in reviews.values() if r.get("review_status") == "verified")
    rejected = sum(1 for r in reviews.values() if r.get("review_status") == "rejected")

    lines = [
        "# Batch CHD curation review packet",
        "",
        f"Generated: {today()}",
        "",
        "This file is generated by `scripts/curation/02_export_review_packet.py`.",
        "It is a working document, not evidence. Automatic matches only enter the",
        "graph after a row in `literature/curated/batch_chd_review.csv` is marked",
        "`verified`, and the build re-checks every quote against PubMed.",
        "",
        f"- queue rows: **{len(queue)}**",
        f"- automatic candidates waiting for review: **{len(approved)}**",
        f"- rows still needing manual reading: **{len(waiting)}**",
        f"- review outcome: **{verified} verified**, **{rejected} rejected**",
        "",
        "## Automatic candidates",
        "",
    ]

    for i, row in enumerate(approved, start=1):
        study = studies.get(row["pmid"])
        lines.append(f"### {i}. PMID {row['pmid']}: {row.get('title', '')}")
        lines.append("")
        lines.append(
            f"- Journal/year: {row.get('journal', '')} ({row.get('year', '')})"
        )
        lines.append(f"- Automatic call: **{row['exposure_id']} -> {row['phenotype_id']}**")
        lines.append(
            f"- Study design / species: {row.get('study_design', '')} / {row.get('species', '')}"
        )
        lines.append(f"- Automatic effect text: `{row.get('effect_direction', '')}`")
        lines.append(f"- Automatic population: {row.get('population_or_model', '')}")
        lines.append(f"- Automatic window: {row.get('exposure_window', '')}")
        review = reviews.get((row["pmid"], row["exposure_id"], row["phenotype_id"]))
        if review:
            lines.append(
                f"- Review: **{review.get('review_status', '')}**. {review.get('review_note', '')}"
            )
        else:
            lines.append("- Review: **pending**")
        lines.append("")
        lines.append("**Matched sentence (verbatim):**")
        lines.append("")
        lines.append(f"> {row.get('quote', '')}")
        lines.append("")
        if study and study.abstract:
            lines.append("**Full abstract:**")
            lines.append("")
            for paragraph in study.abstract.split("\n"):
                if paragraph.strip():
                    lines.append(paragraph.strip())
                    lines.append("")
        else:
            lines.append("_Abstract not available._")
            lines.append("")

    lines.append("## Rows still needing manual reading")
    lines.append("")
    reasons = Counter(r.get("reason", "") for r in waiting)
    for reason, count in reasons.most_common():
        lines.append(f"- {count}: {reason}")
    lines.append("")
    lines.append("| PMID | Title | Year | Candidate exposures | Candidate phenotypes |")
    lines.append("|---|---|---|---|---|")
    for row in waiting:
        title = (row.get("title") or "").replace("|", "/")[:110]
        lines.append(
            f"| {row.get('pmid', '')} | {title} | {row.get('year', '')} | "
            f"{row.get('candidate_exposures', '')} | "
            f"{row.get('candidate_phenotypes', '')} |"
        )
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
