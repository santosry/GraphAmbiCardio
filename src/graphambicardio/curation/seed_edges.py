"""Manually curated anchor evidence (Fase C/G).

Every entry below was read by the study team.  ``quote`` must be a verbatim
fragment of the indexed abstract; the build script verifies this against the
retrieved PubMed record and fails if the fragment is absent.  This is a
deliberately small, high-traceability seed set, not a systematic extraction of
all retrieved literature.

Species / design codes
----------------------
direct_human          epidemiological association in humans
experimental_human    functional experiment with human cells
experimental_animal   in vivo animal experiment
experimental_cell     cell-line experiment
indirect              synthesis/indirect support (review, intermediate steps)
"""

from __future__ import annotations

from typing import Any

E = dict  # readability alias


def edge(
    src: str,
    src_type: str,
    tgt: str,
    tgt_type: str,
    rel: str,
    *,
    ev: str,
    design: str,
    species: str,
    quote: str,
    pmid: str,
    population: str = "",
    window: str = "",
    direction: str = "",
    context: str = "",
    notes: str = "",
    layer: str = "observed",
) -> dict[str, Any]:
    return E(
        source_id=src,
        source_type=src_type,
        target_id=tgt,
        target_type=tgt_type,
        relation=rel,
        evidence_type=ev,
        study_design=design,
        species=species,
        quote=quote,
        reference=pmid,
        reference_type="PMID",
        population_or_model=population,
        exposure_window=window,
        effect_direction=direction,
        context=context,
        notes=notes,
        layer=layer,
    )


